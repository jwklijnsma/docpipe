"""
GitOps delivery: put the generated pages into a docs repository and open (or
update) a GitLab merge request, so docs go through the same review as code.

  1. shallow-clone the docs repo (base branch) into a temp dir
  2. reset the rolling branch (publish.branch) onto the base branch
  3. copy docpipe-generated pages into publish.target_dir (only files with the
     docpipe marker; hand-written pages are never touched)
  4. regenerate index pages + mkdocs.yml over everything in the repo
  5. commit; skip the push if the branch already has exactly this content
  6. force-push the rolling branch and create/update the merge request

The rolling branch is rebuilt every run: fix content in the source repos or
the docpipe config, not on the MR branch.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import tempfile
from datetime import date
from pathlib import Path
from urllib.parse import quote

import requests

from docpipe import __version__
from docpipe.config import Config
from docpipe.log import StageLogger
from docpipe.scan import auth_url, git, scrub
from docpipe.site import MARKER, split_front_matter, write_site

STATUS = {"A": "added", "M": "updated", "D": "removed", "R": "renamed"}


def gitlab_target(cfg: Config) -> tuple[str | None, str | None]:
    """(api base URL, project path) derived from publish.repo unless set explicitly."""
    pub = cfg.publish
    host = path = None
    m = re.match(r"^https?://(?:[^@/]+@)?([^/]+)/(.+?)(?:\.git)?/?$", pub.repo)
    if m:
        host, path = f"https://{m.group(1)}", m.group(2)
    m = re.match(r"^(?:ssh://)?git@([^:/]+)[:/](.+?)(?:\.git)?$", pub.repo)
    if m:
        host, path = f"https://{m.group(1)}", m.group(2)
    return pub.api_url or host, pub.project or path


def _token(cfg: Config) -> str | None:
    return os.environ.get(cfg.publish.token_env) or os.environ.get("DOCPIPE_GIT_TOKEN")


def _last_run(cfg: Config) -> dict:
    try:
        return json.loads((cfg.state_dir / "last_run.json").read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def copy_pages(src_root: Path, dest_root: Path, cfg: Config, log: StageLogger) -> int:
    copied = 0
    for f in sorted(src_root.rglob("*.md")):
        rel = f.relative_to(src_root)
        if rel.name == "index.md":
            continue                       # regenerated over the whole repo below
        text = f.read_text(encoding="utf-8")
        if MARKER not in text:
            continue
        dst = dest_root / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text, encoding="utf-8")
        copied += 1
    if cfg.publish.prune and dest_root.exists():
        known = {s.label for s in cfg.sources}
        for f in sorted(dest_root.rglob("*.md")):
            text = f.read_text(encoding="utf-8", errors="replace")
            if f.name == "index.md" or MARKER not in text:
                continue
            meta, _ = split_front_matter(text)
            if meta.get("source") not in known:
                f.unlink()
                log.info("Pruned %s (source %s no longer configured)", f.relative_to(dest_root), meta.get("source"))
    return copied


def describe(changes: list[tuple[str, str]], cfg: Config) -> str:
    run = _last_run(cfg)
    results = run.get("results", [])
    lines = ["## Automatic documentation update", "",
             f"Generated by docpipe {__version__} with model `{run.get('model', cfg.llm.model)}` "
             f"on {date.today().isoformat()}.", "", "### Changed pages", "",
             "| Change | File |", "|---|---|"]
    lines += [f"| {STATUS.get(s[:1], s)} | `{p}` |" for s, p in changes[:60]]
    if len(changes) > 60:
        lines.append(f"| … | {len(changes) - 60} more |")
    if results:
        lines += ["", "### Sources in the last run", "", "| Source | Type | Revision | Status |", "|---|---|---|---|"]
        lines += [f"| {r['name']} | {r.get('type') or '-'} | `{r.get('revision') or '-'}` | {r['status']} |"
                  for r in results]
    attention = [(r["name"], i) for r in results for i in (r.get("issues") or [])] + \
                [(r["name"], r["error"]) for r in results if r.get("error")]
    if attention:
        lines += ["", "### ⚠️ Needs attention", ""]
        lines += [f"- **{n}**: {i}" for n, i in attention[:30]]
    langs = {p.split("/")[1] for _, p in changes if p.count("/") >= 2}
    lines += ["", "### Review checklist", "",
              "- [ ] Commands, URLs and hostnames are correct",
              "- [ ] No credentials or internal-only details that should not be published"]
    if "nl" in langs:
        lines.append("- [ ] Dutch pages read naturally (B1, consistent form of address)")
    lines += ["", "> This branch is rebuilt on every run. Fix content in the source repositories "
              "or the docpipe configuration, not on this branch."]
    return "\n".join(lines)


def merge_request(cfg: Config, description: str, log: StageLogger) -> str | None:
    pub = cfg.publish
    api, project = gitlab_target(cfg)
    if not (api and project):
        log.warning("No GitLab API/project known for %s — branch pushed, no merge request created", pub.repo)
        return None
    token = _token(cfg)
    if not token:
        raise RuntimeError(f"set {pub.token_env} to create the merge request")
    s = requests.Session()
    s.headers["PRIVATE-TOKEN"] = token
    base = f"{api.rstrip('/')}/api/v4/projects/{quote(project, safe='')}/merge_requests"
    r = s.get(base, params={"state": "opened", "source_branch": pub.branch,
                            "target_branch": pub.base_branch}, timeout=30)
    r.raise_for_status()
    body = {"title": ("Draft: " if pub.draft else "") + pub.title, "description": description,
            "labels": ",".join(pub.labels)}
    if r.json():
        iid = r.json()[0]["iid"]
        r = s.put(f"{base}/{iid}", json=body, timeout=30)
        action = "Updated"
    else:
        body.update(source_branch=pub.branch, target_branch=pub.base_branch,
                    remove_source_branch=True, squash=pub.squash)
        if pub.reviewer_ids:
            body["reviewer_ids"] = pub.reviewer_ids
        r = s.post(base, json=body, timeout=30)
        action = "Created"
    if r.status_code >= 400:
        raise RuntimeError(f"GitLab API {r.status_code}: {scrub(r.text[:300])}")
    url = r.json().get("web_url")
    log.success("%s merge request: %s", action, url)
    return url


def publish(cfg: Config, log: StageLogger, dry_run: bool = False) -> int:
    pub = cfg.publish
    if not pub.repo:
        log.error("publish.repo is not set")
        return 2
    out = Path(cfg.pipeline.output_dir)
    if not out.is_dir() or not any(out.rglob("*.md")):
        log.error("Nothing to publish in %s — run `docpipe run` first", out)
        return 2

    tmp = Path(tempfile.mkdtemp(prefix="docpipe-publish-"))
    try:
        work = tmp / "docs"
        log.git("Cloning docs repository %s (%s)...", pub.repo, pub.base_branch)
        git("clone", "--depth", "1", "--quiet", "--branch", pub.base_branch,
            auth_url(pub.repo, _token(cfg)), str(work))
        git("checkout", "-q", "-B", pub.branch, cwd=work)

        copied = copy_pages(out, work / pub.target_dir, cfg, log)
        log.info("Copied %d generated page(s) into %s/", copied, pub.target_dir)
        if cfg.site.enabled and pub.write_mkdocs:
            write_site(cfg, work / pub.target_dir, work / "mkdocs.yml", pub.target_dir, log)

        git("add", "-A", cwd=work)
        changed = subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=work).returncode == 1
        if not changed:
            log.success("Docs repository already up to date — nothing to publish")
            return 0
        changes = [tuple(l.split("\t", 1)) for l in
                   git("diff", "--cached", "--name-status", cwd=work).splitlines() if "\t" in l]
        log.info("%d file(s) changed: %s", len(changes),
                 ", ".join(f"{STATUS.get(s[:1], s)} {p}" for s, p in changes[:8]))

        results = _last_run(cfg).get("results", [])
        msg = f"docs: update {len(changes)} file(s) [docpipe]\n\n" + "\n".join(
            f"- {r['name']}" + (f" @ {r['revision']}" if r.get("revision") else "") for r in results)
        git("-c", f"user.name={pub.author_name}", "-c", f"user.email={pub.author_email}",
            "commit", "-q", "-m", msg, cwd=work)

        if dry_run:
            log.info("Dry run — not pushing. Merge request description would be:\n%s", describe(changes, cfg))
            return 0

        tree = git("rev-parse", "HEAD^{tree}", cwd=work)
        if git("ls-remote", "--heads", "origin", pub.branch, cwd=work):
            git("fetch", "-q", "--depth", "1", "origin", pub.branch, cwd=work)
            if git("rev-parse", "FETCH_HEAD^{tree}", cwd=work) == tree:
                log.info("Branch %s already contains exactly these changes — no push needed", pub.branch)
                merge_request(cfg, describe(changes, cfg), log)
                return 0
        git("push", "-q", "--force", "origin", f"HEAD:refs/heads/{pub.branch}", cwd=work)
        log.git("Pushed %s", pub.branch)
        merge_request(cfg, describe(changes, cfg), log)
        return 0
    except (RuntimeError, requests.RequestException) as exc:
        log.error("Publish failed: %s", scrub(str(exc)))
        return 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
